import { createHash } from "node:crypto";
import { readFile, writeFile } from "node:fs/promises";
import { join } from "node:path";

const args = process.argv.slice(2);
const sourceDirectories = args.filter(arg => arg !== "--check");
if (sourceDirectories.length !== 1 || sourceDirectories[0].startsWith("--")) {
  throw new Error("Usage: node scripts/generate-dashboard-fonts.mjs <fontsource-directory> [--check]");
}

const fonts = [
  { packageName: "archivo", fileName: "archivo-latin-wdth-normal.woff2", exportName: "archivoFont" },
  { packageName: "jetbrains-mono", fileName: "jetbrains-mono-latin-wght-normal.woff2", exportName: "jetbrainsMonoFont" },
];
const sources = await Promise.all(fonts.map(async font => {
  const directory = join(sourceDirectories[0], font.packageName);
  const [bytes, license, packageText] = await Promise.all([
    readFile(join(directory, "files", font.fileName)),
    readFile(join(directory, "LICENSE"), "utf8"),
    readFile(join(directory, "package.json"), "utf8"),
  ]);
  const metadata = JSON.parse(packageText);
  const packageName = `@fontsource-variable/${font.packageName}`;
  if (metadata?.name !== packageName || typeof metadata.version !== "string") {
    throw new Error(`Invalid font package: ${directory}`);
  }
  if (bytes.subarray(0, 4).toString() !== "wOF2") throw new Error(`Invalid WOFF2 font: ${font.fileName}`);
  return {
    declaration: `export const ${font.exportName} = Buffer.from(${JSON.stringify(bytes.toString("base64"))}, "base64");`,
    notice: `${packageName}@${metadata.version}\nSource: files/${font.fileName}\nSHA-256: ${createHash("sha256").update(bytes).digest("hex")}\nBEGIN LICENSE ${packageName}\n${license}\nEND LICENSE ${packageName}`,
  };
}));
const licenses = `Hotplate dashboard fonts\nGenerated by scripts/generate-dashboard-fonts.mjs.\nRegenerate: node scripts/generate-dashboard-fonts.mjs <fontsource-directory>\n\n${sources.map(source => source.notice).join("\n\n")}\n`;
const generated = `import { Buffer } from "node:buffer";\n\n${sources.map(source => source.declaration).join("\n\n")}\n\nexport const fontLicenses = ${JSON.stringify(licenses)};\n`;
const output = new URL("../src/dashboard/fonts.ts", import.meta.url);
if (args.includes("--check")) {
  if (await readFile(output, "utf8") !== generated) throw new Error("Dashboard fonts are out of date");
  process.stdout.write("Dashboard fonts match their sources.\n");
} else {
  await writeFile(output, generated);
  process.stdout.write("Generated src/dashboard/fonts.ts.\n");
}
